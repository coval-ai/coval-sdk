"""Validate generated dual-package releases before pushing or publishing."""

from __future__ import annotations

import argparse
import os
import re
import subprocess
from pathlib import Path

import release_versions


def git(*arguments: str) -> str:
    return subprocess.check_output(["git", *arguments], text=True).strip()


def validate(mode: str, tag: str | None = None) -> None:
    contents = {name: Path(name).read_text() for name in release_versions.VERSION_FILES}
    if mode == "baseline":
        versions = [
            release_versions.version_tuple(value[1:])
            for value in git("tag", "--merged", "HEAD", "--list", "v*").splitlines()
            if re.fullmatch("v" + release_versions.VERSION_PATTERN, value)
        ]
        current = max(
            map(
                release_versions.version_tuple,
                release_versions.package_versions(contents),
            )
        )
        if not versions or max(versions) < current:
            raise ValueError(
                "Configure a reachable v0.9.2 migration baseline before releasing."
            )
        return
    if not tag or not re.fullmatch("v" + release_versions.VERSION_PATTERN, tag):
        raise ValueError("Release tag must be vMAJOR.MINOR.PATCH.")
    version = tag[1:]
    if contents != release_versions.synchronized(contents, version):
        raise ValueError("Release tag must match every package and runtime version.")
    if git("rev-parse", tag + "^{commit}") != git("rev-parse", "HEAD"):
        raise ValueError("Release tag must identify the checked-out release commit.")
    if git("show", "-s", "--format=%s", "HEAD") != f"chore(release): {version}":
        raise ValueError("Release commit must be generated by release tooling.")
    if git("show", "-s", "--format=%an <%ae>", "HEAD") != (
        "Coval Release Automation <coval-release-automation[bot]@users.noreply.github.com>"
    ):
        raise ValueError("Release commit must be authored by the release App.")
    if len(git("rev-list", "--parents", "-n", "1", "HEAD").split()) != 2:
        raise ValueError("Release commit must have exactly one parent.")
    files = set(
        git("diff-tree", "--no-commit-id", "--name-only", "-r", "HEAD").splitlines()
    )
    if files != {*release_versions.VERSION_FILES, "CHANGELOG.md"}:
        raise ValueError(
            "Release commit may only update all versions and the changelog."
        )
    previous = {
        name: subprocess.check_output(["git", "show", "HEAD^:" + name], text=True)
        for name in release_versions.VERSION_FILES
    }
    if any(
        release_versions.version_tuple(version) <= release_versions.version_tuple(old)
        for old in release_versions.package_versions(previous)
    ):
        raise ValueError("Release must advance beyond both existing package versions.")
    if contents != release_versions.synchronized(previous, version):
        raise ValueError("Release changes must be limited to version metadata.")
    if not re.search(
        rf"^## v{re.escape(version)}\s", Path("CHANGELOG.md").read_text(), re.MULTILINE
    ):
        raise ValueError("Release requires a generated changelog entry.")
    if git("status", "--porcelain"):
        raise ValueError("Release requires a clean checkout.")
    if mode == "prepared":
        if git("rev-parse", "HEAD^") != git("rev-parse", "origin/main"):
            raise ValueError("Release must be prepared from current main.")
    else:
        if os.environ.get("GITHUB_ACTOR") != "coval-release-automation[bot]":
            raise ValueError("Release tag must be pushed by the release App.")
        subprocess.run(
            ["git", "merge-base", "--is-ancestor", "HEAD", "origin/main"], check=True
        )


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("mode", choices=("baseline", "prepared", "tag"))
    parser.add_argument("tag", nargs="?")
    args = parser.parse_args()
    validate(args.mode, args.tag)


if __name__ == "__main__":
    main()
